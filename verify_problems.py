# --- 2. 변형 문제 (Variation Problems) ---
# V1 (이등분선 2개 교차):
# 평행사변형 ABCD에서 ∠A와 ∠B의 이등분선이 각각 대변과 만나는 점을 E, F라 하자.
# AB=10, BC=16 일 때, 선분 EF의 길이는?
# A의 이등분선 => BC 위 E => BE = AB = 10.
# B의 이등분선 => AD 위 F => AF = AB = 10.
# EF는? 그림에서 F는 AD 위(A에서 10), E는 BC 위(B에서 10).
# 사각형 ABEF는 네 변이 모두 10인 마름모! 따라서 EF = 10.
# (또는 대변 AD 위에서 두 이등분선이 모두 만나는 경우:
# AB=6, AD=10. A 이등분선이 CD 연장선 또는 AD 위 E, B 이등분선 F.
# AD 위에서 두 이등분선이 각각 E, F에서 만날 때: AF=6, DE=6 => 중복구간 EF = 6+6-10 = 2!)
# 이 변형이 훨씬 흥미롭고 시험 최빈출:
# "AB=6, BC=10. ∠A의 이등분선과 BC의 교점이 E, ∠B의 이등분선과 AD의 교점이 F"
# 혹은 "∠A의 이등분선과 ∠B의 이등분선이 모두 대변 AD와 만나는 점을 각각 E, F라 하자."
# AE는 A에서 출발하여 AD 위의 점이 아니라 BC와 만나거나,
# 만약 둘 다 AD와 만난다면: ∠A의 이등분선은 AD와 만날 수 없으니(A가 꼭짓점), ∠B의 이등분선과 ∠C의 이등분선이 AD와 만남!
# ∠B 이등분선 -> AD 위 점 E => AE = AB = 6.
# ∠C 이등분선 -> AD 위 점 F => DF = CD = 6.
# AD=10 이므로 겹치는 선분 EF의 길이는: AE + DF - AD = 6 + 6 - 10 = 2 cm! (완벽한 기출 변형!)

# V2 (네 내각 이등분선으로 만든 사각형의 대각선):
# 평행사변형 ABCD의 네 내각의 이등분선의 교점으로 만들어지는 사각형 EFGH는 직사각형이다.
