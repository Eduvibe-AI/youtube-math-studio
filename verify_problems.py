# AB=8, BC=15, BD=17. 겹친 △EBD의 둘레?
# ED = EB = x. AE = 15 - x. (15-x)^2 + 8^2 = x^2 => 225 - 30x + 64 = 0 => 30x = 289 => x = 289/30.
# 더 깔끔한 중2 RPM 변형:
