# T1 (공식 1 유사 - 이등분선 엇각):
# 평행사변형 ABCD, AB=7, AD=11, ∠B의 이등분선이 AD와 만나는 점 E. ED의 길이는?
# △ABE 이등변 => AE = AB = 7 => ED = AD - AE = 11 - 7 = 4. (정답: 4)

# T2 (공식 2 유사 - 이등분선 직교):
