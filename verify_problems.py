# 정리: 평행사변형 네 내각 이등분선 사각형의 대각선 길이 = |BC - AB| = 12 - 7 = 5!
# 검증: 평행선 사이 수선의 발 거리 = 12 - 7 = 5. (정답: 5 cm)

# V3 (종이 2번 접기):
