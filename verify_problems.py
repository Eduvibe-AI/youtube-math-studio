# 접었으므로 ∠DBC' = ∠DBC = 30° => ∠CBC' = 60°.
# AD // BC 이므로 엇각 ∠APB = ∠PBC' = 60° - 30° = 30° 또는 조건에 맞게 설계!

# V4 (외심 + 각의 삼등분):
